"""scripts/new-entity.py --backend: make a mocked entity real. Writes api/routes/<plural>.py (from
scripts/templates/entity/route.py) and its contract test (tests/test_entity_<plural>.py), relists every backed entity
in api/routes/entity_routes.py (handler.py and admin_handler.py route through it), adds the entity's filter parameters
to the CloudFront cache key (cdk API_CACHE_QUERY_KEYS) and turns its browser mock off."""

from __future__ import annotations

import re
from pathlib import Path

from . import ROOT
from .entities import contract_dict, set_mock_flags
from .files import Writer, render
from .spec import Entity, entities

ROUTES = ROOT / "api" / "routes"
TESTS = ROOT / "tests"
TEMPLATES = ROOT / "scripts" / "templates" / "entity"
TAKEN = {"items", "account", "admin", "billing", "cards", "support", "wallet", "webhooks", "entity_routes", "__init__"}
FILTERABLE = {"enum", "ref", "bool", "tags", "int"}


def module_of(e: Entity) -> str:
    return f"entity_{e.module}" if e.module in TAKEN else e.module


def route_file(e: Entity) -> Path:
    return ROUTES / f"{module_of(e)}.py"


def backed(spec: dict) -> list[Entity]:
    return [e for e in entities(spec) if route_file(e).exists()]


def stack_file() -> Path:
    hits = sorted((ROOT / "cdk" / "lib").glob("*-stack.ts"))
    if not hits:
        raise SystemExit("cdk/lib/*-stack.ts not found")
    return hits[0]


def filter_names(e: Entity) -> list[str]:
    return [f["name"] for f in e.fields if f["type"] in FILTERABLE]


def route_py(e: Entity) -> str:
    c = contract_dict(e)
    fields = "\n".join(f"        {meta!r}," for meta in c["fields"])
    filters = "\n".join(f'        "{n}": params.query(event, "{n}"),' for n in filter_names(e))
    return render((TEMPLATES / "route.py").read_text(encoding="utf-8"), {
        "__Entities__": e.Plural, "__Entity__": e.name, "__entity__": e.key, "__plural__": e.plural, "__KIND__": e.kind,
        "__owner__": e.owner, "__public__": str(e.public), "__titleField__": e.title_field,
        "__defaultSort__": c["defaultSort"], "__pageSize__": str(c["pageSize"]), "__fields__": fields,
        "__filters__": filters,
    })


def test_py(e: Entity) -> str:
    return render((TEMPLATES / "test_contract.py").read_text(encoding="utf-8"), {
        "__Entities__": e.Plural, "__entity__": e.key, "__plural__": e.plural, "__routeModule__": module_of(e),
    }, {"userWrites": e.user_writes})


def write_entity_routes(w: Writer, spec: dict) -> None:
    mods = [module_of(e) for e in backed(spec)]
    imports = ", ".join(mods)
    text = f'''"""Generated by scripts/new-entity.py --backend: the spec's entities that have a real backend (api/lib/entities.py).
handler.py routes the user API through route(), admin_handler.py adds ADMIN_ROUTES. Don't edit: re-run the script."""

from __future__ import annotations

try:
    from lib import entities{f"""
    from routes import {imports}""" if mods else ""}
except ImportError:
    from api.lib import entities{f"""
    from api.routes import {imports}""" if mods else ""}

MODULES: list = [{imports}]

# entity name -> its DynamoDB kind, for checking ref ids
KINDS = {{m.ENTITY.name: m.ENTITY.kind for m in MODULES}}


def route(method: str, path: str, user_id: str | None, event: dict) -> dict | None:
    for m in MODULES:
        hit = entities.route(m.ENTITY, method, path, user_id, event, m.filters(event), KINDS)
        if hit is not None:
            return hit
    return None


ADMIN_ROUTES = [r for m in MODULES for r in entities.admin_routes(m.ENTITY, m.filters, KINDS)]
'''
    w.plain(ROUTES / "entity_routes.py", text)


def add_cache_keys(w: Writer, names: list[str]) -> None:
    path = stack_file()
    src = path.read_text(encoding="utf-8")
    m = re.search(r"(API_CACHE_QUERY_KEYS\s*=\s*\[)([^\]]*)(\])", src)
    if not m:
        raise SystemExit(f"{path}: API_CACHE_QUERY_KEYS not found")
    keys = sorted(set(re.findall(r"'([^']+)'", m.group(2))) | set(names))
    w.plain(path, src[:m.start(2)] + ", ".join(f"'{k}'" for k in keys) + src[m.end(2):])


def generate(w: Writer, spec: dict, e: Entity) -> None:
    w.generated(route_file(e), route_py(e), source="scripts/templates/entity/route.py", comment="#")
    w.generated(TESTS / f"test_entity_{e.module}.py", test_py(e), source="scripts/templates/entity/test_contract.py",
                comment="#")
    write_entity_routes(w, spec)
    add_cache_keys(w, filter_names(e))
    set_mock_flags(w, {e.plural: False})
