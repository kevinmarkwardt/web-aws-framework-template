"""JWT verification: Cognito tokens, plus username-only test tokens on the test stage.

Test login (test stage only: STAGE=test and TEST_LOGIN=1, both set by the CDK stack): POST /api/test-login {username}
returns an HS256 token signed with the key in Secrets Manager TEST_LOGIN_SECRET_NAME (yourapp/test/test-login,
generated by the stack). No password, no email: it exists so you (and automated checks) can walk through the test site
without Cognito sign-up mail. It is never on in prod: the prod stack sets neither variable and the secret only exists
in the test stack.
"""

from __future__ import annotations

import os
import json
import time
import urllib.request

from jose import jwk, jwt
from jose.utils import base64url_decode

USER_POOL_ID = os.environ.get("USER_POOL_ID", "")
USER_POOL_CLIENT_ID = os.environ.get("USER_POOL_CLIENT_ID", "")
REGION = os.environ.get("AWS_REGION", "us-east-1")

_jwks_cache = None
_jwks_cache_time = 0
JWKS_CACHE_TTL = 3600  # 1 hour


def _get_jwks():
    global _jwks_cache, _jwks_cache_time
    now = time.time()
    if _jwks_cache and (now - _jwks_cache_time) < JWKS_CACHE_TTL:
        return _jwks_cache
    url = f"https://cognito-idp.{REGION}.amazonaws.com/{USER_POOL_ID}/.well-known/jwks.json"
    with urllib.request.urlopen(url, timeout=5) as resp:  # a slow Cognito must not hold the request for 30 s
        _jwks_cache = json.loads(resp.read())
        _jwks_cache_time = now
    return _jwks_cache


# ---- Test-stage username login ----

TEST_LOGIN = os.environ.get("STAGE") == "test" and os.environ.get("TEST_LOGIN") == "1"
TEST_ISSUER = "yourapp-test-login"
TEST_TOKEN_DAYS = 30
_test_key: str | None = None


def _test_login_key() -> str:
    global _test_key
    if _test_key is None:
        import boto3

        _test_key = boto3.client("secretsmanager", region_name=REGION).get_secret_value(
            SecretId=os.environ["TEST_LOGIN_SECRET_NAME"])["SecretString"]
    return _test_key


def issue_test_token(username: str) -> dict:
    """Test stage only: a token for `username` (user id t-{username}); the profile is created on first GET /api/account."""
    if not TEST_LOGIN:
        raise PermissionError("test login is off")
    now = int(time.time())
    claims = {"sub": f"t-{username}", "email": f"{username}@test.yourapp.com", "name": username,
              "iss": TEST_ISSUER, "iat": now, "exp": now + TEST_TOKEN_DAYS * 86400, "token_use": "id"}
    return {"token": jwt.encode(claims, _test_login_key(), algorithm="HS256"), "userId": claims["sub"],
            "username": username}


# ---- Verification ----

def verify_token(token: str) -> dict:
    """Verify a Cognito JWT (or, on the test stage, a test-login token) and return claims. Raises on invalid token."""
    if TEST_LOGIN and jwt.get_unverified_claims(token).get("iss") == TEST_ISSUER:
        return jwt.decode(token, _test_login_key(), algorithms=["HS256"], issuer=TEST_ISSUER,
                          options={"verify_aud": False})

    jwks = _get_jwks()
    headers = jwt.get_unverified_headers(token)
    kid = headers.get("kid")

    key = None
    for k in jwks.get("keys", []):
        if k["kid"] == kid:
            key = k
            break
    if key is None:
        raise ValueError("Token key ID not found in JWKS")

    public_key = jwk.construct(key)
    message, encoded_sig = token.rsplit(".", 1)
    decoded_sig = base64url_decode(encoded_sig.encode("utf-8"))
    if not public_key.verify(message.encode("utf-8"), decoded_sig):
        raise ValueError("Token signature verification failed")

    claims = jwt.get_unverified_claims(token)
    if claims.get("exp", 0) < time.time():
        raise ValueError("Token expired")
    if claims.get("iss") != f"https://cognito-idp.{REGION}.amazonaws.com/{USER_POOL_ID}":
        raise ValueError("Token issuer mismatch")
    # Only this site's own app client: an ID token names it in aud, an access token in client_id. (The old check let
    # an access token from any client of the pool through.)
    audience = {"id": claims.get("aud"), "access": claims.get("client_id")}.get(claims.get("token_use"))
    if not USER_POOL_CLIENT_ID or audience != USER_POOL_CLIENT_ID:
        raise ValueError("Token audience mismatch")

    return claims


def _bearer(event: dict) -> str:
    headers = event.get("headers") or {}
    auth = headers.get("authorization", headers.get("Authorization", ""))
    return auth[7:] if auth.startswith("Bearer ") else ""


def get_token_claims(event: dict) -> dict:
    """Extract all verified claims from Authorization header."""
    token = _bearer(event)
    if not token:
        return {}
    try:
        return verify_token(token)
    except Exception:
        return {}


def get_user_id(event: dict) -> str | None:
    """Extract and verify user ID from Authorization header. Returns None on failure."""
    return get_token_claims(event).get("sub")
